#include <stdio.h>

#define MaxVNum 100
int G[MaxVNum][MaxVNum];
int n = 14, e = 23;
float W[23] = {39.5, 19.5, 19.5, 29.5, 29.5, 62, 34.5, 24.5,
           37.5, 56.5, 62.5, 92, 46.5, 38.5, 34.5, 56.5,
           88.5, 26.5, 57.5, 71, 43.5, 31.5, 52};
int E[][2] = {{1,2},{2,3},{3,4},{4,14},{14,5},{1,9},{9,8},
              {8,7},{7,5},{9,2},{2,12},{12,13},{2,10},{1,12},
              {12,11},{8,3},{5,10},{10,11},{5,6},{11,13},{6,7},
              {7,14},{3,10}};

int main(void) {
    int i, j, k;

    /* 城市编号为 1～14，第 0 行和第 0 列不使用。 */
    for (i = 1; i <= n; i++) {
        for (j = 1; j <= n; j++) {
            G[i][j] = 0;
        }
    }

    /* 本题构造无权无向图，有边记为 1，暂不使用 W。 */
    for (k = 0; k < e; k++) {
        i = E[k][0];
        j = E[k][1];
        G[i][j] = G[j][i] = 1;
    }

    /* 按城市编号顺序输出 14 × 14 的邻接矩阵。 */
    for (i = 1; i <= n; i++) {
        for (j = 1; j <= n; j++) {
            printf("%d%s", G[i][j], j == n ? "\n" : " ");
        }
    }

    return 0;
}
